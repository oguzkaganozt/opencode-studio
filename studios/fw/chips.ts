const CATALOG: Record<FwChip, FwChipSpec> = {
  esp32: {
    chip: "esp32",
    engine: "qemu",
    qemuSystem: "qemu-system-xtensa",
    qemuArgs: ["-M", "esp32", "-m", "4M"],
    qemuEfuseHex: ESP32_EFUSE,
    capabilities: ["uart"],
  },
  esp32s3: {
    chip: "esp32s3",
    engine: "qemu",
    qemuSystem: "qemu-system-xtensa",
    qemuArgs: ["-M", "esp32s3", "-m", "32M"],
    qemuEfuseHex: ESP32S3_EFUSE,
    capabilities: ["uart"],
  },
  esp32c3: { chip: "esp32c3", engine: "esp-emu", capabilities: ["uart", "gpio", "wifi", "ble"] },
  esp32c6: { chip: "esp32c6", engine: "esp-emu", capabilities: ["uart", "gpio", "wifi", "ble", "thread"] },
  esp32h2: { chip: "esp32h2", engine: "esp-emu", capabilities: ["uart", "gpio", "ble", "thread"] },
  esp32p4: { chip: "esp32p4", engine: "esp-emu", capabilities: ["uart", "gpio"] },
}

export function isFwChip(value: string): value is FwChip {
  return (FW_CHIPS as readonly string[]).includes(value)
}

export function fwChipSpec(chip: string): FwChipSpec {
  if (!isFwChip(chip)) {
    throw new Error(`Unsupported chip '${chip}'. Supported: ${FW_CHIPS.join(", ")}`)
  }
  return CATALOG[chip]
}

export function listFwChips(): FwChipSpec[] {
  return FW_CHIPS.map((chip) => CATALOG[chip])
}

export function fwChipPublic(spec: FwChipSpec) {
  return {
    chip: spec.chip,
    engine: spec.engine,
    capabilities: spec.capabilities,
    uartOnly: spec.engine === "qemu",
  }
}

export function hasFwCapability(spec: FwChipSpec, capability: FwCapability) {
  return spec.capabilities.includes(capability)
}
